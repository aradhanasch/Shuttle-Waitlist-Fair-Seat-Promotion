CREATE TABLE trip (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  capacity INT NOT NULL,
  seats_confirmed INT NOT NULL DEFAULT 0,
  next_request_seq BIGINT NOT NULL DEFAULT 1,
  check_in_cutoff TIMESTAMP WITH TIME ZONE NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT chk_trip_seats CHECK (seats_confirmed >= 0 AND seats_confirmed <= capacity)
);

CREATE TABLE cost_centre_quota (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id BIGINT NOT NULL REFERENCES trip(id),
  cost_centre VARCHAR(50) NOT NULL,
  quota INT NOT NULL,
  seats_used INT NOT NULL DEFAULT 0,
  CONSTRAINT uq_trip_cc UNIQUE (trip_id, cost_centre),
  CONSTRAINT chk_quota CHECK (seats_used >= 0 AND seats_used <= quota)
);

CREATE TABLE booking (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id BIGINT NOT NULL REFERENCES trip(id),
  employee_id VARCHAR(50) NOT NULL,
  cost_centre VARCHAR(50) NOT NULL,
  party_size INT NOT NULL CHECK (party_size >= 1),
  state VARCHAR(20) NOT NULL,
  request_seq BIGINT NOT NULL,
  requested_at TIMESTAMP WITH TIME ZONE NOT NULL,
  tier INT NOT NULL DEFAULT 0,
  skip_count INT NOT NULL DEFAULT 0,
  checked_in_at TIMESTAMP WITH TIME ZONE NULL,
  cancel_reason VARCHAR(30) NULL,
  CONSTRAINT uq_trip_seq UNIQUE (trip_id, request_seq)
);

CREATE INDEX idx_booking_waitlist ON booking(trip_id, state, request_seq);